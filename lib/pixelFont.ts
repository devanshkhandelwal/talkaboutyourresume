/** Width in pixels of `text` in the 3 x 5 font, with 1-pixel gaps. */
export const textWidth3x5 = (text: string) => Math.max(0, text.length * 4 - 1);

/** Draws `text` with its top-left corner at (x, y); unknown characters leave a gap. */
export function drawText3x5(text: string, x: number, y: number, dot: (x: number, y: number) => void) {
  [...text].forEach((ch, i) =>
    FONT_3X5[ch]?.forEach((row, dy) => [...row].forEach((c, dx) => c === "#" && dot(x + i * 4 + dx, y + dy))),
  );
}
